class CompleteOnly:
    """The oldest kind of fake backend: a name, warnings and `complete`, nothing else."""

    name = "fake"

    def __init__(self, reply="ok"):
        self.warnings = []
        self.reply = reply

    def complete(self, system, messages, model, max_tokens):
        return self.reply


class Judging(CompleteOnly):
    """Answers the judge (empty system prompt) with a pass and the caller with a hang up."""

    def complete(self, system, messages, model, max_tokens):
        return '{"pass": true, "reason": "fine", "turn": null}' if system == "" else "<END_CALL>"


PERSONA = {"id": "p", "name": "P", "language": "en", "tags": [], "opening": "hello", "persona": "a caller",
           "expectations": "agent greets", "sop_rule": "r", "fix_hint": "h"}


def test_proxy_records_role_tokens_and_keeps_backend_identity():
    inner = CompleteOnly("x" * 40)
    inner.warnings = ["careful"]
    inner.requested = "claude-cli"
    meter = Meter()
    caller = MeteredBackend(inner, "caller", meter)
    judge = MeteredBackend(inner, "judge", meter)
    assert (caller.name, caller.warnings, caller.requested) == ("fake", ["careful"], "claude-cli")
    assert caller.complete("s" * 8, [{"role": "user", "content": "y" * 12}], "m", 50) == "x" * 40
    judge.complete("", [{"role": "user", "content": "z" * 100}], "m", 50)
    judge.complete("", [{"role": "user", "content": "z" * 100}], "m", 50)
    assert meter.snapshot() == {
        "caller": {"input_tokens": 5, "output_tokens": 10},    # ceil(20 / 4), ceil(40 / 4)
        "judge": {"input_tokens": 50, "output_tokens": 20},    # two calls: 25 in and 10 out each
    }


def test_cli_tokens_are_estimated_from_chars():
    assert [estimate_tokens(t) for t in ("", "a", "abcd", "abcde")] == [0, 1, 1, 2]
    proc = types.SimpleNamespace(returncode=0, stdout='{"result": "abcdefgh"}', stderr="")
    backend = ClaudeCliBackend(runner=lambda *a, **k: proc, which=lambda _: "/bin/claude")
    meter = Meter()
    assert MeteredBackend(backend, "agent", meter).complete("sys!", MESSAGE, "sonnet", 9) == "abcdefgh"
    assert meter.snapshot()["agent"] == {"input_tokens": 4, "output_tokens": 2}  # ceil(13 / 4), ceil(8 / 4)
    assert not hasattr(backend, "complete_with_usage")


def test_anthropic_usage_is_reported():
    class Messages:
        def create(self, **kwargs):
            text = types.SimpleNamespace(type="text", text="namaste")
            return types.SimpleNamespace(content=[text], usage=types.SimpleNamespace(input_tokens=321, output_tokens=7))

    backend = AnthropicBackend(client=types.SimpleNamespace(messages=Messages()))
    text, usage = backend.complete_with_usage("sys", MESSAGE, "claude-sonnet-5-5", 100)
    assert (text, usage) == ("namaste", {"input_tokens": 321, "output_tokens": 7})
    assert backend.complete("sys", MESSAGE, "claude-sonnet-5-5", 100) == "namaste"
    meter = Meter()
    MeteredBackend(backend, "judge", meter).complete("sys", MESSAGE, "claude-sonnet-5-5", 100)
    assert meter.snapshot()["judge"] == {"input_tokens": 321, "output_tokens": 7}  # the SDK numbers, not chars / 4


def test_simulated_latency_formula():
    assert simulated_latency_ms("") == 250
    assert simulated_latency_ms("a" * 100) == 1250
    assert simulated_latency_ms("namaste") == 320


def test_simulate_usage_counts_each_generated_message():
    transcript = [
        {"role": "user", "content": "u" * 8},        # the opening is scripted, not generated by the caller
        {"role": "assistant", "content": "a" * 20},
        {"role": "user", "content": "c" * 12},
        {"role": "assistant", "content": "b" * 40},
    ]
    usage, latency = simulate_usage({}, transcript, {"agent": "A" * 16, "caller": "C" * 4, "judge": "J" * 400})
    assert usage["agent"] == {"input_tokens": 6 + 14, "output_tokens": 5 + 10}   # (16+8)/4, (16+8+20+12)/4
    assert usage["caller"] == {"input_tokens": 8, "output_tokens": 3}            # (4 + 8 + 20) / 4, 12 / 4
    assert usage["judge"] == {"input_tokens": 200, "output_tokens": 120}         # two runs, 60 tokens out each
    assert latency == [450, 650]


def test_offline_usage_and_latency_are_simulated_and_labelled():
    sop = read_sample_sop()
    backend = OfflineBackend()
    generation = generate_personas(sop, 5, backend)
    results = run_suite(example_agent.respond, generation.personas, 1, 8, 2, backend, 0)
    assert all(r.latency_label == "simulated" and r.usage and r.turn_latency_ms for r in results)
    again = run_suite(example_agent.respond, generation.personas, 1, 8, 2, backend, 0)
    assert [r.usage for r in results] == [r.usage for r in again]  # deterministic
    kwargs = dict(run_id="r", sop_text=sop, agent={"id": "v1", "label": "v1"}, backend=backend, callers=5,
                  max_turns=8, generation=generation, results=results, seconds=1.0, synthetic=True)
    plain = build_report(**kwargs)
    assert plain["cost"] is None and plain["latency"] is None  # the caller switches metering on
    report = build_report(**kwargs, metering=True, budget_ms=500)
    cost, latency = report["cost"], report["latency"]
    assert cost["label"] == "simulated" and latency["label"] == "simulated" and cost["currency"] == "USD"
    assert set(cost["by_role"]) == {"caller", "agent", "judge"}
    assert cost["by_role"]["judge"]["output_tokens"] == 5 * 120  # 5 calls, two judge runs of 60 tokens
    assert cost["total"] == pytest.approx(sum(r["cost"] for r in cost["by_role"].values()))
    assert cost["per_call"] == pytest.approx(cost["total"] / 5, abs=1e-6)  # both rounded to 6 places
    assert cost["prices"] == {k: load_prices()[k] for k in ("source_url", "retrieved_on")}
    every_turn = [ms for call in report["calls"] for ms in call["turn_latency_ms"]]
    assert latency["turns"] == len(every_turn) == sum(len(r.turn_latency_ms) for r in results)
    assert latency["budget_ms"] == 500 and latency["over_budget"] == sum(ms > 500 for ms in every_turn)
    assert latency["p50_ms"] == percentile(every_turn, 50) and latency["p95_ms"] == percentile(every_turn, 95)
    assert all(set(call["usage"]) == {"caller", "agent", "judge"} for call in report["calls"])


def test_live_run_meters_caller_and_judge_and_times_agent_turns():
    class Live(Judging):
        name = "claude-cli"

    result = run_one(lambda history: "Namaste ji", PERSONA, 0, 4, Live(), 0)
    assert result.passed and result.latency_label == "measured" and len(result.turn_latency_ms) == 1
    assert all(ms >= 0 for ms in result.turn_latency_ms)
    assert set(result.usage) == {"caller", "judge"} and result.usage["judge"]["output_tokens"] > 0


def test_percentile_nearest_rank_cases():
    assert percentile([], 50) is None
    assert percentile([7], 95) == 7
    values = [5, 1, 4, 2, 3]
    assert [percentile(values, p) for p in (50, 95, 100, 1)] == [3, 5, 5, 1]
    assert percentile([10, 20, 30, 40], 50) == 20  # ceil(0.5 * 4) - 1 = index 1
    assert percentile(list(range(1, 101)), 95) == 95
    assert percentile(list(range(1, 21)), 95) == 19 and percentile(list(range(1, 21)), 90) == 18
    assert values == [5, 1, 4, 2, 3]  # input untouched
    block = latency_block([100, 200, 900, 1600], "measured", 1500)
    assert block == {"label": "measured", "p50_ms": 200, "p95_ms": 1600, "budget_ms": 1500, "turns": 4,
                     "over_budget": 1}
    assert latency_block([1500], "simulated", 1500)["over_budget"] == 0  # only strictly over the budget counts
    assert latency_block([], "simulated", 1500)["p50_ms"] is None


