def test_cost_is_tokens_times_price_per_million():
    models = {"caller": "sonnet", "agent": "claude-sonnet-5-5", "judge": "claude-sonnet-5-5"}  # an alias works too
    block = cost_block(USAGE, models, PRICES, "estimated", calls=4)
    assert block["by_role"]["caller"] == {"input_tokens": 1_000_000, "output_tokens": 0, "cost": 2.0}
    assert block["by_role"]["agent"]["cost"] == 3.0 and block["by_role"]["judge"]["cost"] == 0.0
    assert (block["total"], block["per_call"], block["unknown_models"]) == (5.0, 1.25, [])
    assert (block["label"], block["currency"]) == ("estimated", "USD")
    assert block["prices"] == {"source_url": "https://example.test/pricing", "retrieved_on": "2026-11-06"}


def test_unknown_price_gives_null_cost_and_names_model():
    models = {"caller": "claude-haiku-5-5", "agent": "claude-sonnet-5-5", "judge": "claude-mystery-9"}
    usage = copy.deepcopy(USAGE)
    usage["judge"] = {"input_tokens": 10, "output_tokens": 10}
    block = cost_block(usage, models, PRICES, "reported", calls=2)
    assert block["total"] is None and block["per_call"] is None
    assert block["by_role"]["caller"]["cost"] is None and block["by_role"]["judge"]["cost"] is None
    assert block["by_role"]["agent"]["cost"] == 3.0  # known prices still show per role
    assert block["unknown_models"] == ["claude-haiku-5-5", "claude-mystery-9"]
    # a model with no tokens cannot make the total unknown
    quiet = cost_block(USAGE, {**models, "judge": "claude-mystery-9"}, PRICES, "reported", calls=1)
    assert quiet["unknown_models"] == ["claude-haiku-5-5"] and quiet["by_role"]["judge"]["cost"] == 0.0


def test_pricing_file_has_source_date_and_verify_note():
    prices = load_prices()
    assert prices["source_url"].startswith("https://")
    datetime.date.fromisoformat(prices["retrieved_on"])
    assert "verify" in prices["note"].lower() and prices["currency"] == "USD"
    for entry in prices["models"].values():
        for side in ("input", "output"):
            assert entry[side] is None or (isinstance(entry[side], (int, float)) and entry[side] >= 0)
    assert prices["aliases"]["sonnet"] == "claude-sonnet-5-5" and prices["aliases"]["haiku"] == "claude-haiku-5-5"
    for _, _, default in ROLE_MODELS.values():
        assert default in prices["models"]  # every default model has a row, even if its price is null


def _edited(tmp_path, mutate):
    data = yaml.safe_load(PRICING.read_text(encoding="utf-8"))
    mutate(data)
    path = tmp_path / "pricing.yaml"
    path.write_text(yaml.safe_dump(data), encoding="utf-8")
    return path


@pytest.mark.parametrize("mutate", [
    lambda d: d.update(schema_version=2),
    lambda d: d.pop("source_url"),
    lambda d: d.update(source_url=""),
    lambda d: d.update(retrieved_on="06/11/2026"),
    lambda d: d.update(retrieved_on="2026-13-40"),
    lambda d: d.update(note="Snapshot of published prices."),
    lambda d: d["per_million_tokens"].update({"claude-sonnet-5-5": {"input": -1, "output": 1}}),
    lambda d: d["per_million_tokens"].update({"claude-sonnet-5-5": {"input": "2", "output": 1}}),
    lambda d: d["per_million_tokens"].update({"claude-sonnet-5-5": {"input": 2}}),
    lambda d: d["aliases"].update(sonnet="claude-nope-1"),
    lambda d: d.pop("per_million_tokens"),
])
def test_bad_pricing_files_are_refused(tmp_path, mutate):
    with pytest.raises(PricingError):
        load_prices(_edited(tmp_path, mutate))


def test_null_prices_are_valid(tmp_path):
    def blank(d):
        for entry in d["per_million_tokens"].values():
            entry.update(input=None, output=None)
    assert load_prices(_edited(tmp_path, blank))["models"]["claude-sonnet-5-5"] == {"input": None, "output": None}


