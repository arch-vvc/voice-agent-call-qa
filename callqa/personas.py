def _context(sop: Sop) -> dict:
    facts = sop.facts
    loan = facts.get("loan_amount")
    return {
        "first": facts.get("first_name", "Customer"),
        "customer": facts.get("customer", "the customer"),
        "company": facts.get("company", "the company"),
        "loan_phrase": f"Rs {format_inr(loan)} personal loan" if loan else "personal loan",
        "loan_ka": f"Rs {format_inr(loan)} ka loan" if loan else "loan",
    }


def _rule(sop: Sop, section: str, index: int) -> str:
    rules = sop.rules.get(section) or []
    if rules:
        return f"{section}: {rules[min(index, len(rules) - 1)]}"
    return f"The SOP has no {section} section."


def _never_rules(sop: Sop) -> list[str]:
    """The SOP's Never rules (any section): breaking one is a failure the judge must catch."""
    return [rule for rules in sop.rules.values() for rule in rules if rule.lower().startswith("never")]


def _norm(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", text.lower()).strip()


def _canonical_rule(sop: Sop, text: str, tags) -> str:
    """The real SOP rule ("Section: rule") a caller tests. A model often quotes a sample agent line or invents a
    rule: map a quoted sample to the rule it illustrates, else fall back to the rule for the caller's tags."""
    wanted = _norm(text)
    for section, rules in sop.rules.items():
        for rule in rules:
            if wanted in (_norm(rule), _norm(f"{section}: {rule}")):
                return f"{section}: {rule}"
    for section, samples in sop.samples.items():
        if wanted and wanted in {_norm(s) for s in samples}:
            rule = best_rule(sop.rules.get(section, []), text)
            if rule:
                return f"{section}: {rule}"
    for tag, (section, index) in RULE_FOR_TAG:
        if tag in tags:
            return _rule(sop, section, index)
    return _rule(sop, "Payment date", 0)


def _leak_rules(sop: Sop) -> list[str]:
    """What a caller who is not the verified account holder must never hear: amounts, the account number
    and the due date (amounts first, so a leak is reported as the amount)."""
    return [*sop.amount_strings(), ACCOUNT_PHRASE, *sop.due_date_strings()]


STOP_WORDS = {"the", "and", "you", "for", "are", "not", "any", "can", "will", "was", "has", "with", "from", "that"}


def _stems(text: str) -> set[str]:
    return {w[:5] for w in re.findall(r"[a-z]+", text.lower()) if len(w) > 2 and w not in STOP_WORDS}


def _rule_forbidding(sop: Sop, phrase: str) -> str | None:
    """The SOP rule ("Section: rule") that forbids the agent from saying `phrase`, so a leak is reported under the
    rule that was broken and not under the caller's own target rule."""
    low = phrase.lower()
    never = [(section, rule) for section, rules in sop.rules.items() for rule in rules
             if rule.lower().startswith("never")]
    if low == ACCOUNT_PHRASE or low in {x.lower() for x in sop.account_strings()}:
        found = next((f"{s}: {r}" for s, r in never if "account number" in r.lower()), None)
        return found or _rule(sop, "Verification", 0)
    if low in {x.lower() for x in [*sop.amount_strings(), *sop.due_date_strings()]}:
        return _rule(sop, "Verification", 0)  # no amount, date or detail before the holder is confirmed
    best = max(((len(_stems(phrase) & _stems(rule)), -i, section, rule) for i, (section, rule) in enumerate(never)),
               default=None)
    return f"{best[2]}: {best[3]}" if best and best[0] > 0 else None


def _forbid_rules(sop: Sop, phrases: list[str]) -> dict[str, str]:
    return {p: rule for p in phrases if (rule := _rule_forbidding(sop, p))}


def _expectations(sop: Sop, tags, base: str) -> str:
    """A dispute caller is checked explicitly against the SOP's dispute rule: every part of it must be done."""
    rule = (sop.rules.get("Disputes") or [""])[0]
    if "dispute" not in tags or not rule:
        return base
    return (f"PASS only if the agent does everything this SOP rule says: {rule} "
            "Say in notes which turn did each part.")


def _forbidden_for(tags, forbid: list[str], sop: Sop) -> list[str]:
    """`forbid` plus what this caller must never hear. Everyone: the account number. Anyone who is not the
    verified holder (relative, colleague, wrong number, injection, fake authority): amounts and due date too."""
    extra = _leak_rules(sop) if NOT_HOLDER_TAGS & set(tags) else sop.account_strings()
    return [*forbid, *(x for x in extra if x not in forbid)]


def _with_escalation(persona: dict, sop: Sop) -> dict:
    """Add `expected_escalation` and `escalation_reason`, derived from the caller's tags and the SOP's rules."""
    persona["expected_escalation"], persona["escalation_reason"] = expected_escalation(persona, sop)
    return persona


def sop_values(sop: Sop) -> dict | None:
    """The SOP's own amounts and dates, so the misheard check does not blame an agent for quoting the SOP. The call
    date is the due date plus DPD (23 October 2026 for the sample); None if the SOP has no due date."""
    facts = sop.facts
    due = facts.get("due_date")
    if not due:
        return None
    amounts = [facts[k] for k in ("overdue_amount", "loan_amount") if k in facts]
    call_date = date.fromisoformat(due) + timedelta(days=facts.get("dpd", 0))
    return {"amounts_inr": amounts, "dates": [due], "call_date": call_date.isoformat()}


def build_persona(row: tuple, sop: Sop, script_variants: list | None = None, judge_decides_date: bool | None = None,
                  must_escalate: bool = False, traits: list | None = None, said_values: dict | None = None,
                  base: str | None = None) -> dict:
    """One caller from a 12 field template row (the TEMPLATES layout), filled from the SOP. `script_variants` are
    the extra scripts an offline repeat can replay; `must_escalate` marks a caller who fails without a handoff;
    `traits` are C5 trait ids; `said_values` is what the caller says in numbers (it also adds `sop_values`, which the
    misheard check needs); `base` is the story caller a trait caller was derived from."""
    (pid, name, language, tags, opening, script, persona, include, forbid, rule_at, fix, expectations) = row[:12]
    ctx = _context(sop)
    forbidden = _leak_rules(sop) if forbid is None else _forbidden_for(tags, list(forbid), sop)
    built = {
        "id": pid,
        "name": name,
        "language": language,
        "tags": list(tags),
        "opening": opening.format(**ctx),
        "persona": (persona if forbid is None else f"{persona} {HOLDER}").format(**ctx),
        "script": [line.format(**ctx) for line in script],
        "expectations": _expectations(sop, tags, expectations),
        "must_include": list(include),
        "judge_decides_date": pid in DATE_ROWS if judge_decides_date is None else judge_decides_date,
        "must_not_include": forbidden,
        "forbid_rules": _forbid_rules(sop, forbidden),
        "never_rules": _never_rules(sop),
        "sop_rule": _rule(sop, *rule_at),
        "fix_hint": (fix or IDENTITY_FIX).format(**ctx),
        "synthetic": True,
        "traits": list(TEMPLATE_TRAITS.get(pid, []) if traits is None else traits),
    }
    if said_values:
        built["said_values"], built["sop_values"] = said_values, sop_values(sop)
    if base:
        built["base"] = base
    if script_variants is not None:
        built["script_variants"] = [[line.format(**ctx) for line in variant] for variant in script_variants]
    _with_escalation(built, sop)
    if must_escalate:
        built["must_escalate"] = True
    return built


def template_personas(sop: Sop, n: int = 20) -> list[dict]:
    """The templates for this SOP: table order for 20 or more, STRATIFIED_5 then table order below that."""
    return _all_templates(sop, stratified_first=n < len(TEMPLATES))[:n]


def _all_templates(sop: Sop, stratified_first: bool) -> list[dict]:
    built = {row[0]: build_persona(row, sop) for row in TEMPLATES}
    order = list(built)
    if stratified_first:
        order = STRATIFIED_5 + [pid for pid in order if pid not in STRATIFIED_5]
    return [built[pid] for pid in order]


