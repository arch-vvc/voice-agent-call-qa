def _slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", str(text).lower()).strip("_")


def _text(value) -> str | None:
    return value.strip() if isinstance(value, str) and value.strip() else None


def _strings(value) -> list[str] | None:
    if value is None:
        return []
    if isinstance(value, list) and all(isinstance(x, str) for x in value):
        return [x.strip() for x in value if x.strip()]
    return None


def _validate(item) -> dict | None:
    """One persona from the model, or None if it cannot run through the harness."""
    if not isinstance(item, dict):
        return None
    pid = _slugify(item.get("id") or item.get("name") or "")
    opening, script = _text(item.get("opening")), item.get("script")
    include, forbid = _strings(item.get("must_include")), _strings(item.get("must_not_include"))
    tags = item.get("tags", [])
    if not (pid and opening and isinstance(script, list) and 1 <= len(script) <= 6):
        return None
    if not (all(isinstance(x, str) and x.strip() for x in script) and include is not None and forbid is not None):
        return None
    if item.get("language") not in ("en", "hinglish") or not isinstance(tags, list):
        return None
    sop_rule = _text(item.get("sop_rule")) or ""
    return {
        "id": pid,
        "name": _text(item.get("name")) or pid,
        "language": item["language"],
        "tags": [t for t in tags if t in TAGS],
        "traits": [t for t in TRAIT_IDS if t in (item["traits"] if isinstance(item.get("traits"), list) else [])],
        "opening": opening,
        "persona": _text(item.get("persona")) or opening,
        "script": script,
        "expectations": _text(item.get("expectations")) or "PASS if the agent follows the SOP. FAIL otherwise.",
        "must_include": include,
        "judge_decides_date": False,
        "must_not_include": forbid,
        "sop_rule": sop_rule,
        "fix_hint": _text(item.get("fix_hint")) or f"Follow the SOP rule: {sop_rule}",
        "synthetic": True,
    }


def _parse_reply(reply: str) -> list[dict]:
    start, end = reply.find("["), reply.rfind("]")
    if start < 0 or end < start:
        raise ValueError("no JSON array in the reply")
    items = json.loads(reply[start:end + 1])
    if not isinstance(items, list):
        raise ValueError("the reply is not a JSON array")
    return [p for p in map(_validate, items) if p]


def _dedupe(personas: list[dict]) -> list[dict]:
    seen: set[str] = set()
    for p in personas:
        base, i = p["id"], 2
        while p["id"] in seen:
            p["id"] = f"{base}_{i}"
            i += 1
        seen.add(p["id"])
    return personas


def _enforce_mix(personas: list[dict], sop: Sop, n: int, warnings: list[str]) -> list[dict]:
    """At least one Hinglish, one adversarial and one trait caller: replace the last items with templates if not."""
    from callqa.persona_sets import trait_caller  # persona_sets builds on this module, so import it late

    templates = {p["id"]: p for p in template_personas(sop, 20)}
    templates["hindi_amount_partial"] = trait_caller(sop)
    protected: set[str] = set()
    needs = (
        ("wants_manager", "Hinglish", lambda p: p["language"] == "hinglish"),
        ("brother_asks", "adversarial", lambda p: "adversarial" in p["tags"]),
        ("hindi_amount_partial", "trait", lambda p: bool(p.get("traits"))),
    )
    for tid, label, ok in needs:
        if any(ok(p) for p in personas):
            continue
        personas = [p for p in personas if p["id"] != tid]
        replaceable = [i for i, p in enumerate(personas) if p["id"] not in protected]
        if len(personas) >= n and replaceable:
            personas.pop(replaceable[-1])
        personas.append(templates[tid])
        protected.add(tid)
        warnings.append(f"No {label} caller in the generated set; replaced the last one with {tid}")
    return personas


def _from_llm(sop: Sop, sop_text: str, n: int, backend) -> GenerationResult:
    from callqa.persona_sets import apply_trait

    system = SYSTEM_PROMPT.format(n=n, tags=", ".join(sorted(TAGS)), traits=", ".join(TRAIT_IDS))
    user = f"Write {n} callers for this SOP.\n\n--- SOP ---\n{sop_text}"
    reply = backend.complete(system, [{"role": "user", "content": user}], model_for("gen"), 8000)
    personas = _dedupe(_parse_reply(reply))[:n]
    if not personas:
        raise ValueError("no valid personas in the reply")

    warnings: list[str] = []
    for i, p in enumerate(personas):
        for trait in p["traits"]:
            personas[i] = p = apply_trait(p, trait)
        p["must_not_include"] = _forbidden_for(p["tags"], p["must_not_include"], sop)
        p["sop_rule"] = _canonical_rule(sop, p["sop_rule"], p["tags"])
        p["forbid_rules"] = _forbid_rules(sop, p["must_not_include"])
        p["expectations"] = _expectations(sop, p["tags"], p["expectations"])
        p["never_rules"] = _never_rules(sop)
        _with_escalation(p, sop)
    if len(personas) < n:
        have = {p["id"] for p in personas}
        extra = [p for p in _all_templates(sop, True) if p["id"] not in have]
        personas += extra[: n - len(personas)]
        warnings.append(f"Only some generated callers were valid; topped up to {len(personas)} from templates")
    return GenerationResult(_enforce_mix(personas, sop, n, warnings), "llm", warnings)


def generate_personas(sop_text: str, n: int = 20, backend=None, story: bool = False) -> GenerationResult:
    """n callers for this SOP. Never calls the backend if it is None or offline, or if `story` is set and n is at
    most 5: the dashboard's default five are the fixed story set, not a sample."""
    if n < 1:
        raise ValueError("n must be at least 1")
    sop = parse_sop(sop_text)
    if backend is None or backend.name == "offline" or (story and n <= len(STRATIFIED_5)):
        return GenerationResult(template_personas(sop, n), "templates", [])
    try:
        return _from_llm(sop, sop_text, n, backend)
    except BackendError as exc:
        if exc.kind in ABORT_KINDS:
            raise
        reason = f"backend {exc.kind}: {exc}"
    except (ValueError, TypeError) as exc:  # json.JSONDecodeError is a ValueError
        reason = f"malformed output: {exc}"
    return GenerationResult(
        template_personas(sop, n),
        f"templates (LLM failed: {reason})",
        [f"Persona generation failed ({reason}); using templates"],
    )


def to_yaml(personas: list[dict]) -> str:
    return HEADER + yaml.safe_dump(personas, sort_keys=False, allow_unicode=True, width=100)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Generate synthetic caller personas from a collections SOP.")
    p.add_argument("sop", help="path to the SOP markdown file")
    p.add_argument("--out", required=True, help="YAML file to write")
    p.add_argument("--backend", default=None, help="offline | claude-cli | anthropic (default: env or claude-cli)")
    p.add_argument("--callers", type=int, default=None, help="how many callers (default 20 offline, 5 otherwise)")
    args = p.parse_args(argv)

    backend = get_backend(args.backend)
    n = args.callers or (20 if backend.name == "offline" else 5)
    result = generate_personas(Path(args.sop).read_text(encoding="utf-8"), n, backend)
    Path(args.out).write_text(to_yaml(result.personas), encoding="utf-8")
    for warning in [*backend.warnings, *result.warnings]:
        print(f"warning: {warning}", file=sys.stderr)
    print(f"source: {result.source}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
